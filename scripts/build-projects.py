#!/usr/bin/env python3
"""Generate assets/js/projects-data.js from index.html cards + each project page.

Run from the repo root:  python3 scripts/build-projects.py
Reads the OLD card markup in index.html the first time; after the redesign it
reads the cached assets/js/projects-seed.json instead.
"""
import json, re, html, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
seed_path = root / "assets/js/projects-seed.json"

def strip(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()

if not seed_path.exists():
    idx = (root / "index.html").read_text()
    cards = re.findall(
        r'<div class="col-lg-4 col-md-6 portfolio-item">\s*<img src="([^"]+)"[^>]*alt="([^"]*)">\s*'
        r'<div class="portfolio-info">\s*<h4>(.*?)</h4>\s*<p>(.*?)</p>\s*<a href="([^"]+)"', idx, re.S)
    seed = [dict(img=c[0], alt=html.unescape(c[1]), title=strip(c[2]), blurb=strip(c[3]).lstrip("/ "), href=c[4]) for c in cards]
    seed_path.write_text(json.dumps(seed, indent=1, ensure_ascii=False))
seed = json.loads(seed_path.read_text())

CAT = {  # category per project page (filter chips on the home page)
 "project-asic2.html":"chips", "project-asic1.html":"chips", "project-sram.html":"chips",
 "project-alu.html":"chips", "project-mcp.html":"chips",
 "project-fpga-final.html":"fpga", "project-fpga1.html":"fpga", "project-fpga2.html":"fpga", "project-fpga3.html":"fpga",
 "project-galton.html":"embedded", "project-birdsong.html":"embedded", "project-ikiwiki.html":"embedded", "project-vu.html":"embedded",
 "project-riffMIDI.html":"music", "project-midi.html":"music",
}
HOOK = {  # short, page-sourced headline chips shown on each card
 "project-asic2.html":["Taped out · validating","Smith-Waterman DNA alignment"],
 "project-fpga-final.html":["AES-128","DE1-SoC + VGA"],
 "project-riffMIDI.html":["Arduino Mega 2560","Guitar → MIDI"],
 "project-asic1.html":["Taped out · validating","TSMC 180nm","Popcount unit"],
 "project-fpga1.html":["Lorenz ODE solver","DE1-SoC"],
 "project-fpga2.html":["Mandelbrot","Parallelized","DE1-SoC"],
 "project-fpga3.html":["2D wave equation","Drum synth","DE1-SoC"],
 "project-galton.html":["16,900 balls","60 fps","350 MHz"],
 "project-birdsong.html":["50 kHz DDS","SPI DAC","Merlin Bird ID"],
 "project-midi.html":["Java","Live MIDI","Velocity-colored notes"],
 "project-sram.html":["1 KB 6T","600 ps cycle","14.2 fJ/bit"],
 "project-alu.html":["4-bit","10 operations"],
 "project-ikiwiki.html":["Gyroscope control","PyGame"],
 "project-mcp.html":["Pipelined RISC-V","Multicore"],
 "project-vu.html":["ADC → LED bar","ARM Cortex-M0+"],
}
FEATURED = {"project-asic2.html","project-fpga-final.html","project-galton.html"}
out = []
for p in seed:
    page = (root / p["href"]).read_text()
    info = re.search(r'<div class="portfolio-info">\s*<h3>.*?</h3>\s*<ul>(.*?)</ul>', page, re.S)
    facts = []
    if info:
        for li in re.findall(r"<li>(.*?)</li>", info.group(1), re.S):
            m = re.match(r"\s*<strong>(.*?):?</strong>\s*(.*)", li, re.S)
            if m: facts.append([strip(m.group(1)).rstrip(":"), strip(m.group(2))])
    tags = [strip(t) for t in re.findall(r'<span class="tag">(.*?)</span>', page, re.S)]
    summ = re.search(r"<h3>Summary</h3>\s*<p>(.*?)</p>", page, re.S)
    out.append(dict(p, cat=CAT.get(p["href"], "embedded"), hook=HOOK.get(p["href"], []), featured=p["href"] in FEATURED, facts=facts, tags=tags,
                    summary=strip(summ.group(1)) if summ else ""))
(root / "assets/js/projects-data.js").write_text(
    "// generated by scripts/build-projects.py — do not edit by hand\nwindow.PROJECTS = "
    + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
print(len(out), "projects")
for o in out: print(o["cat"], "|", o["title"], "|", o["facts"][:3], "|", o["tags"][:3])


# ---- site-data.js: courses + songs (parsed once from the old index.html into site-seed.json)
site = json.loads((root / "assets/js/site-seed.json").read_text())
AREA = {"ECE 2300":"hw","ECE 3150":"hw","ECE 4740":"hw","ECE 4750":"hw","ECE 6745":"hw","ECE 5760":"hw","ECE 3140":"hw",
        "CS 1110":"sw","CS 2110":"sw","ECE 2720":"sw","ECE 2100":"sig","ECE 3250":"sig","ECE 3030":"sig"}
courses = []
for c in site["courses"]:
    m = re.match(r"((?:ECE|CS|MATH) \d{4}):?\s*(.*)", re.sub(r"<[^>]+>", "", c["desc"]))
    code = m.group(1) if m else ""
    if c["group"].startswith("Math"): area = "math"
    elif code: area = AREA.get(code, "hw")
    else: area = "sw"                       # online certificates (Python, C++)
    link = re.search(r'href="([^"]+)"', c["desc"])
    courses.append(dict(code=code or "Certificate", title=html.unescape(c["title"]),
                        desc=(m.group(2) if m and m.group(2) else ""), area=area, link=link.group(1) if link else ""))
songs = [dict(title=x["title"], kind=x["group"], src=x["src"]) for x in site["songs"]]
(root / "assets/js/site-data.js").write_text(
    "// generated by scripts/build-projects.py — do not edit by hand\nwindow.COURSES = "
    + json.dumps(courses, indent=1, ensure_ascii=False) + ";\nwindow.SONGS = "
    + json.dumps(songs, indent=1, ensure_ascii=False) + ";\n")
print(len(courses), "courses,", len(songs), "songs")
